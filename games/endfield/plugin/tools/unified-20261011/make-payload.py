"""Build a hash-pinned payload from audited, unmodified runtime files.

Two NR runtimes ship in one package. The payload table maps GPU architecture to
the runtime this machine will load, and the bridge verifies the selected file at
startup; the user installs one package for RTX 20 through 50 and never chooses.

* Blackwell (0x1b0): the NVIDIA-signed 310.8.0.0 build, sm_120 only.
* Turing/Ampere/Ada (0x160/0x170/0x190): the multi-generation build, whose
  fatbin carries sm_75/86/89/120 and whose host-side minimum-architecture
  constant is relaxed to match.
"""
from pathlib import Path
import hashlib, json, shutil, sys

root = Path(__file__).resolve().parents[2]
game = Path('C:/Program Files/Hypergryph Launcher/games/Arknights Endfield')
# Game interposer builds the 2.14.1 plugin directory is accepted with, oldest
# first. Both report Streamline 2.10.3; the second shipped with every other SL
# and NGX file byte-identical to the first build's game directory. A failed
# redirect is still rolled back by the startup health policy.
VERIFIED_INTERPOSERS = [
    '39925bb5216ee1b3d164d1b9dac9e127869c2bcd7ea60f29c1c24b416de7a1f4',
    'fabb19bb6495d743182c1bc51bcbbdc4481acc3dcaf445403f0b304a31a56ccc',
]
out = Path(sys.argv[1]) if len(sys.argv) > 1 else root / 'dist/unified-20261011o-payload-staging'
sl = ['sl.common.dll','sl.deepdvc.dll','sl.dlss.dll','sl.dlss_d.dll','sl.dlss_g.dll','sl.pcl.dll','sl.reflex.dll','nvngx_dlssg.dll','nvngx_dlss.dll','nvngx_dlssd.dll','nvngx_deepdvc.dll']
records = []
for name in sl:
    src = game/'dlss5/sl-2.14.1'/name
    dst = out/'dlss5/sl-2.14.1'/name
    dst.parent.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    if dst.exists():
        assert hashlib.sha256(dst.read_bytes()).hexdigest() == digest
    else:
        shutil.copy2(src, dst)
    assert hashlib.sha256(dst.read_bytes()).hexdigest() == digest
    records.append({'path':str(dst.relative_to(out)).replace('\\','/'), 'sha256':digest,'source':str(src)})

# The runtimes and the architectures they serve. Ampere and Ada share one file
# with Turing: the multi-generation build is the only one that carries their
# cubins, so a per-generation split would ship the same bytes twice.
runtimes = [
    {'source': root/'downloads/pr-20261001-verify/nr/nvngx_dlssnr.dll',
     'path': 'dlss5/nr/rtx50/nvngx_dlssnr.dll',
     'label': '310.8.0.0 (RTX 50)',
     'architectures': {'Blackwell': '0x1b0'}},
    {'source': root/'evidence/global-tone-native-20260920/sf-v2-nvngx_dlssnr.dll',
     'path': 'dlss5/nr/rtx20-40/nvngx_dlssnr.dll',
     'label': '310.8 multi-generation (RTX 20-40)',
     'architectures': {'Turing': '0x160', 'Ampere': '0x170', 'Ada': '0x190'}},
]
nr_mapping = {}
nr_records = []
for runtime in runtimes:
    src = runtime['source']
    dst = out/runtime['path']
    dst.parent.mkdir(parents=True, exist_ok=True)
    digest = hashlib.sha256(src.read_bytes()).hexdigest()
    if dst.exists():
        assert hashlib.sha256(dst.read_bytes()).hexdigest() == digest, runtime['path']
    else:
        shutil.copy2(src, dst)
    assert hashlib.sha256(dst.read_bytes()).hexdigest() == digest
    records.append({'path':str(dst.relative_to(out)).replace('\\','/'),'sha256':digest,'source':str(src)})
    runtime['sha256'] = digest
    nr_records.append({'path': runtime['path'], 'sha256': digest, 'label': runtime['label']})
    for generation, arch in runtime['architectures'].items():
        nr_mapping[generation] = {'path': runtime['path'], 'architecture': arch}

manifest = out/'payload-manifest.json'
assert not manifest.exists(), 'Do not overwrite an existing release manifest'
manifest.write_text(json.dumps({'files':records,'nr_mapping':nr_mapping,'nr_runtimes':nr_records,'status':'candidate; cross-machine acceptance pending'},ensure_ascii=False,indent=2),encoding='utf-8')

def lines_for(runtime, name):
    entries = ', '.join(runtime['architectures'].values()) + ', 0'
    return [
        'inline constexpr NrRuntime ' + name + '{',
        '    L"' + runtime['path'] + '",',
        '    "' + runtime['sha256'] + '",',
        '    "' + runtime['label'] + '",',
        '    {' + entries + '}};',
    ]

lines=['#pragma once','// Generated by tools/unified-20261011/make-payload.py; do not edit by hand.','#include <cstdint>','namespace dlss5::payload {','struct Entry { const wchar_t* leaf; const char* hash; };','inline constexpr Entry sl[] = {']
for item in records[:len(sl)]:
    lines.append('  {L"'+item['path'].split('/')[-1]+'", "'+item['sha256']+'"},')
current_interposer = hashlib.sha256((game/'sl.interposer.dll').read_bytes()).hexdigest()
assert current_interposer in VERIFIED_INTERPOSERS, 'unverified game interposer: ' + current_interposer
lines+=['};',
        "// The game's own sl.interposer.dll builds the 2.14.1 plugin directory is",
        '// accepted with. Both are Streamline 2.10.3: the first is the Hypergryph build',
        '// shipped until 2026-10 (581,096 bytes, extra export HGSetupCustomVulkan), the',
        '// second the NVIDIA-signed build (569,472 bytes, 2.10.3.9a2e2760) shipped by',
        '// the 2026-10-15 game update with every other SL and NGX file unchanged. Any',
        '// other interposer keeps the game directory; a redirect that fails at startup',
        '// is rolled back by the deployment health policy.',
        'inline constexpr const char* interposers[] = {']
lines+=['  "'+h+'",' for h in VERIFIED_INTERPOSERS]
lines+=['};',
        'inline bool KnownInterposer(const char* sha256) {',
        '  if (sha256 == nullptr) return false;',
        '  for (const char* known : interposers) {',
        '    const char* a = known; const char* b = sha256;',
        '    while (*a && *a == *b) { ++a; ++b; }',
        '    if (*a == 0 && *b == 0) return true;',
        '  }',
        '  return false;',
        '}','']
lines+=['// NR runtimes. Every build the package ships is listed here with the GPU',
        '// architectures it may serve, so the choice is a table lookup instead of a',
        '// decision scattered through the code. The user installs one package and never',
        '// chooses; SelectionForArchitecture below answers which file this machine runs.',
        '//',
        '// Blackwell (0x1b0) uses the NVIDIA-signed 310.8.0.0 build: it carries only',
        '// sm_120 and reports "Unsupported GPU architecture" for anything older, and it',
        '// is the combination verified in game on the RTX 5090 development machine.',
        '//',
        '// Turing, Ampere and Ada (0x160, 0x170, 0x190) use the multi-generation build:',
        '// its fatbin carries sm_75, sm_86, sm_89 and sm_120 cubins, and its host-side',
        '// minimum-architecture constant is relaxed to match, so one file serves all',
        '// three without per-generation packages. It is not NVIDIA-signed, so the',
        '// generic-side identity check treats it as a named non-reference build rather',
        '// than a reference match; that path is diagnostics only and never fatal.',
        '//',
        '// Both files keep the name nvngx_dlssnr.dll, so the bridge\'s NR witness and',
        '// Generic\'s module lookups are unaffected by the choice.',
        'struct NrRuntime {',
        '  const wchar_t* path;   // relative to the game directory',
        '  const char* hash;',
        '  const char* label;     // shown in the panel and written to the log',
        '  uint32_t architectures[4];  // NVAPI NV_GPU_ARCH_INFO architecture ids, 0 = end',
        '};','']
lines+=lines_for(runtimes[0], 'nr_blackwell')
lines+=['']
lines+=lines_for(runtimes[1], 'nr_generic')
lines+=['','inline constexpr const NrRuntime* nr_runtimes[] = {&nr_blackwell, &nr_generic};','',
 '// A path that cannot exist in a correct installation: the game directory may',
 '// not contain a bare nvngx_dlssnr.dll beside the executable, so a failure to',
 '// choose cannot silently fall back to a runtime this package did not verify.',
 'inline constexpr const wchar_t* nr_unavailable = L"dlss5-runtime-unavailable/nvngx_dlssnr.dll";','',
 'inline bool NrRuntimeServes(const NrRuntime& runtime, uint32_t architecture) {',
 '  for (const uint32_t candidate : runtime.architectures) {',
 '    if (candidate == 0) return false;',
 '    if (candidate == architecture) return true;',
 '  }',
 '  return false;',
 '}','',
 'inline const NrRuntime* SelectionForArchitecture(uint32_t architecture) {',
 '  if (architecture == 0) return nullptr;',
 '  for (const NrRuntime* runtime : nr_runtimes) {',
 '    if (NrRuntimeServes(*runtime, architecture)) return runtime;',
 '  }',
 '  return nullptr;',
 '}',
 '}  // namespace dlss5::payload']
(root/'src/unified-20261011/common/payload.hpp').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print('Payload copied and verified:',len(records),'files;',len(nr_records),'NR runtimes')
